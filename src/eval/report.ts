import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { SupabaseClient } from "@supabase/supabase-js";
import { DETECTION_CONFIG } from "@/config/detection";
import type {
  EvalKind,
  EvalRecord,
  FalseAlarmSummary,
  HeldOutSummary,
  LoadTestSummary,
  RandomisedSummary,
  ReplaySummary,
  SecuritySummary,
  SensitivitySummary,
} from "./types";

/**
 * Persists evaluation results: eval/results/<kind>.json (gitignored), an eval_runs row (when a
 * service-role key is configured), and the README results table. Every record carries the
 * config_hash of the exact thresholds that produced it, the seed and the git sha.
 */

export const RESULTS_DIR = "eval/results";
export const README_START = "<!-- EVAL:START -->";
export const README_END = "<!-- EVAL:END -->";

/** sha256 of the detection thresholds (src/config/detection.ts), first 16 hex chars. */
export function configHash(): string {
  return createHash("sha256").update(JSON.stringify(DETECTION_CONFIG)).digest("hex").slice(0, 16);
}

export function makeRecord<S, D>(kind: EvalKind, seed: number | null, gitSha: string | null, summary: S, details: D): EvalRecord<S, D> {
  return { kind, created_at: new Date().toISOString(), git_sha: gitSha, config_hash: configHash(), seed, summary, details };
}

export function writeResult(rec: EvalRecord<unknown, unknown>, dir = RESULTS_DIR): string {
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${rec.kind}.json`);
  writeFileSync(path, JSON.stringify(rec, null, 2));
  return path;
}

export function readResults(dir = RESULTS_DIR): Partial<Record<EvalKind, EvalRecord>> {
  const out: Partial<Record<EvalKind, EvalRecord>> = {};
  if (!existsSync(dir)) return out;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".json")) continue;
    try {
      const rec = JSON.parse(readFileSync(join(dir, f), "utf8")) as EvalRecord;
      out[rec.kind] = rec;
    } catch {
      // ignore unreadable files
    }
  }
  return out;
}

/** Inserts an eval_runs row; never throws (a DB outage must not lose the local result). */
export async function insertEvalRun(db: SupabaseClient, rec: EvalRecord<unknown, unknown>): Promise<boolean> {
  try {
    const { error } = await db.from("eval_runs").insert(rec);
    return !error;
  } catch {
    return false;
  }
}

const pct = (x: number | null | undefined, dp = 1) => (x === null || x === undefined ? "n/a" : `${(x * 100).toFixed(dp)}%`);

/** Markdown results table from the latest local results (used by `npm run eval -- --write-readme`). */
export function renderResultsMarkdown(r: Partial<Record<EvalKind, EvalRecord>>): string {
  const lines: string[] = [];
  const meta = (rec: EvalRecord) => `config \`${rec.config_hash}\`, seed ${rec.seed ?? "-"}, git \`${rec.git_sha ?? "-"}\`, ${rec.created_at.slice(0, 16)}Z`;
  lines.push("_Auto-generated by `npm run eval -- --write-readme`. Do not edit by hand._", "");

  const rnd = r.randomised as EvalRecord<RandomisedSummary> | undefined;
  if (rnd) {
    const s = rnd.summary;
    lines.push(`**Randomised attacks** (${s.trials_per_kind} trials per kind; ${meta(rnd)})`, "");
    lines.push("| Attack | Detected | Rate (95% CI) | Median / p90 time to detect | Rules fired | False alarms / trial |", "|---|---|---|---|---|---|");
    for (const k of s.per_kind) {
      lines.push(
        `| ${k.kind} | ${k.detected}/${k.trials} | ${pct(k.detection.rate)} (${pct(k.detection.low)}-${pct(k.detection.high)}) | ${k.median_ttd_min ?? "n/a"} / ${k.p90_ttd_min ?? "n/a"} min | ${Object.entries(k.rules_fired).map(([a, b]) => `${a}×${b}`).join(", ") || "-"} | ${k.false_alarms_per_trial} |`,
      );
    }
    lines.push(`| **overall** | ${s.overall.detected}/${s.overall.trials} | ${pct(s.overall.rate)} (${pct(s.overall.low)}-${pct(s.overall.high)}) | ${s.median_ttd_min ?? "n/a"} min median | | |`, "");
  }
  const fa = r.false_alarm as EvalRecord<FalseAlarmSummary> | undefined;
  if (fa) {
    const s = fa.summary;
    lines.push(`**False alarms** on ${s.days_measured} days × ${s.links} links × ${s.seeds.length} seeds of attack-free traffic (${meta(fa)}): **${s.false_alerts_per_day} false alerts/day** (${s.per_link_per_week} per link per week; ${pct(s.during_viral_bump_share)} during legitimate viral bumps). Per rule/day: ${Object.entries(s.per_rule_per_day).map(([k, v]) => `${k} ${v}`).join(", ")}.`, "");
  }
  const sen = r.sensitivity as EvalRecord<SensitivitySummary> | undefined;
  if (sen) {
    lines.push(`**Sensitivity / breaking points** (${sen.summary.trials_per_level} trials per level; ${meta(sen)})`, "");
    lines.push("| Attack | Parameter | Detection by level | Breaking point (>= 90%) |", "|---|---|---|---|");
    for (const s of sen.summary.series) {
      lines.push(`| ${s.kind} | ${s.parameter} | ${s.levels.map((l) => `${l.level}: ${pct(l.detection.rate, 0)}`).join(", ")} | ${s.breaking_point ?? "not reached"} |`);
    }
    lines.push("");
  }
  const ho = r.held_out as EvalRecord<HeldOutSummary> | undefined;
  if (ho) {
    lines.push(`**Held-out attacks** (not designed for; ${meta(ho)})`, "");
    lines.push("| Attack | Detected | Rate (95% CI) | Why |", "|---|---|---|---|");
    for (const k of ho.summary.per_kind) lines.push(`| ${k.kind} | ${k.detected}/${k.trials} | ${pct(k.detection.rate)} (${pct(k.detection.low)}-${pct(k.detection.high)}) | ${k.note} |`);
    lines.push("");
  }
  const rp = r.replay as EvalRecord<ReplaySummary> | undefined;
  if (rp) {
    const s = rp.summary;
    if (s.skipped) lines.push(`**Replay (TalkingData)**: skipped - dataset not present when the suite last ran.`, "");
    else
      lines.push(
        `**Replay (TalkingData, ${s.rows_valid?.toLocaleString("en-US")} real clicks, ${s.links} channels, ${s.time_span_hours} h; ${meta(rp)})**: alerts ${Object.entries(s.alerts_by_rule ?? {}).map(([k, v]) => `${k} ${v}`).join(", ")}; not applicable: ${(s.not_applicable_rules ?? []).join(", ") || "none"}. Flagged clicks (${pct(s.coverage_share, 2)} of traffic) attribute at ${pct(s.flagged?.rate, 3)} vs ${pct(s.unflagged?.rate, 3)} unflagged: **ratio ${s.attribution_ratio ?? "n/a"}** (z = ${s.z_test?.z}, p = ${s.z_test?.p_value}). IPs that triggered IP_BURST: ratio ${s.burst_ips?.ratio ?? "n/a"} (${s.burst_ips?.ips} IPs).`,
        "",
      );
  }
  const lt = r.load_test as EvalRecord<LoadTestSummary> | undefined;
  if (lt) {
    const s = lt.summary;
    lines.push(`**Redirect load test** (${s.url_host}, ${s.connections} connections, ${s.duration_s} s; ${meta(lt)}): ${s.requests_per_sec} req/s, p50 ${s.p50_ms} ms, p95 ${s.p95_ms} ms, p99 ${s.p99_ms} ms, non-302 ${s.non_302}, errors ${s.errors}.`, "");
  }
  const sec = r.security as EvalRecord<SecuritySummary> | undefined;
  if (sec) lines.push(`**Security checks** against ${sec.summary.target_host}: **${sec.summary.passed}/${sec.summary.total} passed** (${meta(sec)}).`, "");
  if (lines.length === 2) lines.push("No results yet. Run `npm run eval`.");
  return lines.join("\n");
}

/** Replaces the content between the README markers (markers are kept). */
export function replaceBetweenMarkers(readme: string, content: string): string {
  const a = readme.indexOf(README_START);
  const b = readme.indexOf(README_END);
  if (a === -1 || b === -1 || b < a) throw new Error("README markers not found");
  return `${readme.slice(0, a + README_START.length)}\n${content}\n${readme.slice(b)}`;
}
